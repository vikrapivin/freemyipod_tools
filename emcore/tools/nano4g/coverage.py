#!/usr/bin/env python3
"""Generate the M2 migration table from the runnable registry and model report."""
import argparse
from collections import Counter
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from nano4g.experiments import entries


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--report", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--device", type=Path, nargs="*", default=[], help="physical result summaries")
    ap.add_argument("--audit", type=Path, help="classified physical summary from tools/fmss_capture_audit.py")
    args = ap.parse_args()
    observed = {}
    for path in args.device:
        capture = json.loads(path.read_text())
        if capture.get("evidence") != "device":
            raise ValueError("not a physical capture: " + str(path))
        observed.update({name: path.name for name in capture.get("results", {})})
    audited = json.loads(args.audit.read_text()) if args.audit else {}
    for name, entry in audited.get('experiments', {}).items():
        c = entry['counts']
        observed[name] = '%d sampled; %d not executed; %d case errors' % (
            c.get('sampled', 0), c.get('not_executed_setup_or_preflight', 0) + c.get('no_execution_samples', 0), c.get('case_error', 0))
    result = json.loads(args.report.read_text())["results"]
    rows = list(entries(include_followups=True))
    counts = Counter(r["status"] for r in rows)
    text = ['# Chapter 13 — M2 experiment coverage\n\n<a id="m2-experiment-coverage"></a>\n', "Generated by `emCORE/tools/nano4g/coverage.py`.\n",
            "All 142 original names, READ ID and %d follow-up families have runnable entries (%d total). Status counts: " % (counts['followup'], len(rows)) +
            ", ".join(f"{n} {status}" for status, n in sorted(counts.items())) + ".\n",
            "Every family runs resident by default, including `m2_wedge` and `m2_regbus`. "
            "The host uploads manifests, polls progress and collects result pages; "
            "a full result arena resumes the same uploaded manifest. `--isolate-diagnostics` "
            "explicitly collects those two diagnostic families per case; `--single-probes` "
            "opts every family out of batching. The sequence-only `m2_cpu_direct` campaign "
            "groups up to 128 jobs per manifest (1,850 jobs in 15 worker RUNs on p48, M2-727). "
            "Its batch API also supports map jobs, but the campaign contains no map phase.\n",
            "`ported` describes the current M2 implementation, not device qualification. "
            "`partial` retains explicit missing cases; `applicability` does not reproduce "
            "the original operation until the M2 mapping is established. A model run can "
            "stop at its first unsupported case. Physical counts below describe retained summary records, not every native submission or successful semantic check. "
            "Capture notes belong with the capture itself.\n",
            "Model column is the historical report `" + str(args.report) + "`; it is not a fresh model run for the selected physical capture. "
            "Physical audit: `" + str(args.audit or 'none') + "`. Source: `" + audited.get('source', 'not audited') + "`.\n",
            "Original questions are the M1 experiment list. "
            "M2 sources: `emCORE/tools/nano4g/` and shared `emCORE/tools/fmss/experiments/`.\n",
            "| Experiment | Migration | M2 scope / gap | Historical model attempt | Physical retained records |",
            "|---|---|---|---|---|"]
    for row in rows:
        run = result.get(row["name"], {})
        outcome = run.get("status", "not run")
        if run.get("reason"):
            outcome += ": " + run["reason"]
        cells = ("`" + row["name"] + "`", row["status"], row["reason"], outcome, observed.get(row["name"], "not audited"))
        text.append("| " + " | ".join(c.replace("|", "\\|").replace("\n", " ") for c in cells) + " |")
    text += ["", '<a id="additional-matrices"></a>\n\n## 13.1 Additional matrices', "",
             "Run `--followups`, or include them via the device runner's `--all`. "
             "Each case records errors independently. Model outcomes are in "
             "`emCORE/build/m2-followup-model.json`.", "",
             "| Family | Extends M1 experiments | Question |", "|---|---|---|"]
    from nano4g.followup_experiments import entries as followups
    for row in followups():
        text.append("| `%s` | %s | %s |" % (row["name"], row["original"], row["reason"]))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # Claim-level obligations are authored independently of the name registry.
    # Regenerating execution counts must not erase the whole-book test plan.
    marker = '<!-- M2-BOOK-AUDIT:BEGIN -->'
    if args.output.exists():
        previous = args.output.read_text()
        if marker in previous:
            text += ['', previous[previous.index(marker):].rstrip()]
    args.output.write_text("\n".join(text) + "\n")


if __name__ == "__main__":
    main()
